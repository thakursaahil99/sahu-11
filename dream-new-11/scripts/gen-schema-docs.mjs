// Generates docs/SCHEMA.md from apps/api/prisma/schema.prisma (models, fields, enums, indexes).
// Usage: npm run docs:schema
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const schema = readFileSync(join(ROOT, 'apps/api/prisma/schema.prisma'), 'utf8');

const AREAS = [
  ['Accounts & auth', ['User', 'UserSettings', 'OtpCode', 'RefreshToken', 'AuditLog']],
  ['Sports data', ['Sport', 'Series', 'Team', 'Player', 'Match', 'MatchPlayer']],
  ['Fantasy teams', ['FantasyConfig', 'UserTeam', 'UserTeamPlayer']],
  ['Contests & live scoring', ['Contest', 'ContestEntry', 'ScoringConfig', 'MatchLiveState', 'PlayerMatchPoints']],
  ['Wallet (double-entry ledger)', ['WalletAccount', 'WalletTransaction', 'LedgerEntry', 'KycRecord']],
  ['Engagement & safety', ['Notification', 'PushToken', 'SupportTicket', 'SupportMessage', 'PlayLimits']],
  ['Admin', ['RiskFlag', 'Announcement']],
];

const models = new Map();
const enums = new Map();
const blockRe = /((?:\/\/\/[^\n]*\n)*)(model|enum) (\w+) \{([\s\S]*?)\n\}/g;
for (const [, docs, kind, name, body] of schema.matchAll(blockRe)) {
  const doc = docs.replace(/\/\/\/\s?/g, '').trim().replace(/\n/g, ' ');
  if (kind === 'enum') {
    enums.set(name, body.split('\n').map((l) => l.trim()).filter((l) => l && !l.startsWith('//')));
    continue;
  }
  const fields = [];
  const attrs = [];
  let pending = [];
  for (const raw of body.split('\n')) {
    const line = raw.trim();
    if (!line) continue;
    if (line.startsWith('///')) {
      pending.push(line.slice(3).trim());
      continue;
    }
    if (line.startsWith('//')) continue;
    if (line.startsWith('@@')) {
      attrs.push(line);
      continue;
    }
    const m = /^(\w+)\s+([\w\[\]?]+)\s*(.*)$/.exec(line);
    if (!m) continue;
    const [, fname, type, rest] = m;
    const isRelation = /@relation/.test(rest) || (/^[A-Z]/.test(type.replace(/[\[\]?]/g, '')) && !enums.has(type.replace(/[\[\]?]/g, '')) && !['String', 'Int', 'Boolean', 'DateTime', 'Json', 'Float', 'BigInt', 'Decimal'].includes(type.replace(/[\[\]?]/g, '')));
    fields.push({ name: fname, type, attrs: rest.replace(/@relation\([^)]*\)/, '@relation').trim(), doc: pending.join(' '), relation: isRelation });
    pending = [];
  }
  models.set(name, { doc, fields, attrs });
}

const esc = (s) => s.replace(/\|/g, '\\|');
let md = `# Database schema

> Generated by \`npm run docs:schema\` from \`apps/api/prisma/schema.prisma\` — ${models.size} models, ${enums.size} enums. PostgreSQL 16+, managed by Prisma migrations (\`apps/api/prisma/migrations\`).

## Invariants worth knowing

- **Money is integers.** Every amount is stored ×100 (\`…X100\` columns: paise or hundredths of a demo credit). Points are ×10 (\`pointsX10\`, vice-captain 1.5× can make halves).
- **The wallet is a double-entry ledger.** A \`WalletTransaction\` owns \`LedgerEntry\` lines that sum to zero; balances are always \`SUM(amountX100)\` per account and bucket — nothing stores a balance. A database trigger rejects \`UPDATE\` on \`LedgerEntry\`, and every transaction has a unique \`idempotencyKey\` so retries and duplicate webhooks can't double-post. Users with ledger history can't be hard-deleted (FK \`RESTRICT\`): deletion anonymises the user instead.
- **Contests can't overfill.** Joins lock the contest row (\`SELECT … FOR UPDATE\`), and a \`CHECK (filledSpots <= totalSpots)\` constraint backs it up.
- **Timestamps** are UTC \`timestamp(3)\`. In raw SQL compare against \`now() AT TIME ZONE 'UTC'\` (the session time zone may differ).
- **Idempotent side effects** use unique keys: \`Notification(userId, dedupeKey)\`, \`RiskFlag(userId, kind, dedupeKey)\`, \`Contest(matchId, templateKey)\`, \`UserTeam(userId, matchId, signature)\`.
- **Secrets at rest:** passwords are bcrypt; OTPs and refresh tokens are stored as hashes; PANs are masked plus a peppered SHA-256; staff TOTP secrets are AES-256-GCM encrypted.

`;

const listed = new Set();
for (const [area, names] of AREAS) {
  md += `## ${area}\n\n`;
  for (const name of names) {
    const m = models.get(name);
    if (!m) continue;
    listed.add(name);
    md += `### ${name}\n\n${m.doc ? `${m.doc}\n\n` : ''}| Field | Type | Notes |\n| --- | --- | --- |\n`;
    for (const f of m.fields) {
      if (f.relation) continue;
      const notes = [f.attrs.replace(/@default\(([^)]*\)?)\)/, 'default $1').replace(/@/g, ''), f.doc].filter(Boolean).join(' — ');
      md += `| \`${f.name}\` | ${esc(f.type)} | ${esc(notes)} |\n`;
    }
    const rel = m.fields.filter((f) => f.relation).map((f) => `\`${f.name}\` → ${f.type.replace(/[\[\]?]/g, '')}${f.type.endsWith('[]') ? ' (many)' : ''}`);
    if (rel.length) md += `\nRelations: ${rel.join(', ')}.\n`;
    if (m.attrs.length) md += `\nKeys & indexes: ${m.attrs.map((a) => `\`${a.replace(/^@@/, '')}\``).join(', ')}.\n`;
    md += '\n';
  }
}
const missing = [...models.keys()].filter((n) => !listed.has(n));
if (missing.length) throw new Error(`Models without a docs area: ${missing.join(', ')}`);

md += `## Enums\n\n| Enum | Values |\n| --- | --- |\n`;
for (const [name, values] of enums) md += `| \`${name}\` | ${values.map((v) => `\`${v}\``).join(', ')} |\n`;

writeFileSync(join(ROOT, 'docs/SCHEMA.md'), md);
console.log(`docs/SCHEMA.md: ${models.size} models, ${enums.size} enums`);
